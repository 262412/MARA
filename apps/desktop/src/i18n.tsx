const messages: Record<Language, Record<TranslationKey, string>> = {
  en: english,
  zh: chinese,
};

export type Translate = (key: TranslationKey, values?: TranslationValues) => string;

function interpolate(template: string, values?: TranslationValues): string {
  if (!values) {
    return template;
  }
  return template.replace(/{{(\w+)}}/g, (_, key: string) =>
    String(values[key] ?? ""),
  );
}

const defaultTranslate: Translate = (key, values) =>
  interpolate(english[key], values);

type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: Translate;
};

const defaultContext: LanguageContextValue = {
  language: "en",
  setLanguage: () => undefined,
  t: defaultTranslate,
};

const LanguageContext = createContext<LanguageContextValue>(defaultContext);
const LANGUAGE_STORAGE_KEY = "mara.desktop.language";

function readStoredLanguage(): Language {
  if (typeof window === "undefined") {
    return "en";
  }
  try {
    return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === "zh"
      ? "zh"
      : "en";
  } catch {
    return "en";
  }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(readStoredLanguage);
  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next);
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
    } catch {
      // The UI remains usable when browser storage is unavailable.
    }
  }, []);
  const t = useCallback<Translate>(
    (key, values) => interpolate(messages[language][key], values),
    [language],
  );

  useEffect(() => {
    document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  }, [language]);

  const value = useMemo(
    () => ({ language, setLanguage, t }),
    [language, setLanguage, t],
  );
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  return useContext(LanguageContext);
}
